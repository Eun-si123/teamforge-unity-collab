import assert from "node:assert/strict";
import { execFile, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { cp, lstat, mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const execFileAsync = promisify(execFile);
const releaseContract = JSON.parse(await readFile(path.join(root, "release-contract.json"), "utf8"));
const noRestore = process.argv.slice(2).includes("--no-restore");
const launcherRoot = path.join(root, "launcher");
const project = path.join(launcherRoot, "src", "TeamForge.Launcher", "TeamForge.Launcher.csproj");
const pinsPath = path.join(launcherRoot, "src", "TeamForge.Launcher", "RuntimePins.g.cs");
const loaderSource = path.join(launcherRoot, "runtime-loader.mjs");
const runtimeSource = path.join(root, "unity-package", "com.eunsung.teamforge", "Runtime~");
const runtimeManifestSource = path.join(runtimeSource, "runtime-manifest.json");
const outputTarget = path.join(launcherRoot, "win-x64");
const output = path.join(root, "work", `launcher-build-${process.pid}`);
assert.equal(path.dirname(outputTarget), launcherRoot);
assert.equal(path.basename(outputTarget), "win-x64");
assert(output.startsWith(`${path.join(root, "work")}${path.sep}`),
  "Disposable Launcher build root escaped the repository work directory.");
const { stdout: dotnetSdkOutput } = await execFileAsync("dotnet", ["--version"], { cwd: root, windowsHide: true });
const dotnetSdkVersion = dotnetSdkOutput.trim();
assert.equal(dotnetSdkVersion, releaseContract.dotnet.testedSdk,
  "Selected .NET SDK differs from release-contract.json/global.json.");

const sha256 = async (file) => createHash("sha256").update(await readFile(file)).digest("hex");
const runtimeManifestSha256 = await sha256(runtimeManifestSource);
const loaderSha256 = await sha256(loaderSource);
const runtimeManifest = JSON.parse(await readFile(runtimeManifestSource, "utf8"));
assert.equal(runtimeManifest.guestBridgeRelativePath, "backend/project-peer/src/guest-orchestrator-cli.mjs");
assert.equal(runtimeManifest.productVersion, releaseContract.productVersion,
  "Runtime product version differs from release-contract.json.");
assert.equal(runtimeManifest.nodeVersion, releaseContract.node.version,
  "Runtime Node version differs from release-contract.json.");

const pins = `// Generated by scripts/build-wp4-launcher.mjs.\nnamespace TeamForge.Launcher;\n\ninternal static class RuntimePins\n{\n    internal const string ManifestSha256 = "${runtimeManifestSha256}";\n    internal const string LoaderSha256 = "${loaderSha256}";\n}\n`;
await writeFile(pinsPath, pins);

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: false });
await new Promise((resolve, reject) => {
  const publishArguments = [
    "publish", project, "--configuration", "Release", "--runtime", "win-x64", "--self-contained", "true",
    "--output", output, "--nologo", "--disable-build-servers",
  ];
  if (noRestore) publishArguments.push("--no-restore");
  const child = spawn("dotnet", publishArguments,
    { cwd: root, shell: false, windowsHide: true, stdio: "inherit" });
  child.once("error", reject);
  child.once("exit", (code) => code === 0 ? resolve() : reject(new Error(`dotnet publish exited ${code}`)));
});

await cp(loaderSource, path.join(output, "runtime-loader.mjs"), { errorOnExist: true, force: false });
await cp(runtimeSource, path.join(output, "Runtime"), { recursive: true, errorOnExist: true, force: false });
assert.equal(await sha256(path.join(output, "runtime-loader.mjs")), loaderSha256);
assert.equal(await sha256(path.join(output, "Runtime", "runtime-manifest.json")), runtimeManifestSha256);
assert.equal(await sha256(path.join(output, "Runtime", "platforms", "win-x64", "node.exe")),
  runtimeManifest.platforms.find((item) => item.id === "win-x64").sha256);
const runtimeConfig = JSON.parse(await readFile(path.join(output, "TeamForge.Launcher.runtimeconfig.json"), "utf8"));
assert.equal(runtimeConfig.runtimeOptions.tfm, releaseContract.dotnet.targetFramework.replace(/-windows$/u, ""),
  "Published Launcher target framework differs from release-contract.json.");
const includedFrameworks = runtimeConfig.runtimeOptions.includedFrameworks ?? [];
assert(includedFrameworks.length > 0, "Self-contained Launcher runtimeconfig has no included .NET frameworks.");
assert(includedFrameworks.every((item) => item.version === releaseContract.dotnet.runtimeVersion),
  "Published Launcher .NET runtime differs from release-contract.json.");

async function collect(directory, result = []) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Unsafe Launcher publish link: ${target}`);
    if (entry.isDirectory()) await collect(target, result);
    else if (entry.isFile() && entry.name !== "launcher-manifest.json") result.push(target);
    else if (!entry.isFile()) throw new Error(`Unsafe Launcher publish entry: ${target}`);
  }
  return result;
}

const published = (await collect(output)).sort();
assert(published.some((file) => path.basename(file) === "TeamForge.Launcher.exe"), "Launcher EXE is missing.");
assert(!published.some((file) => /\.(?:pdb|xml)$/iu.test(file)), "Debug/symbol artifact leaked into Launcher publish.");
const records = [];
for (const file of published) {
  const info = await lstat(file);
  const relative = path.relative(output, file).split(path.sep).join("/");
  records.push({ path: relative, size: info.size, sha256: await sha256(file) });
}
const launcherManifest = {
  schemaVersion: 1,
  product: "TeamForge Launcher",
  productVersion: releaseContract.productVersion,
  target: releaseContract.target,
  deployment: releaseContract.launcher.deployment,
  signed: releaseContract.launcher.signed,
  targetFramework: releaseContract.dotnet.targetFramework,
  dotnetSdkVersion,
  dotnetRuntimeVersion: releaseContract.dotnet.runtimeVersion,
  runtimeManifestSha256,
  loaderSha256,
  files: records,
};
await writeFile(path.join(output, "launcher-manifest.json"), `${JSON.stringify(launcherManifest, null, 2)}\n`, { flag: "wx" });
await rm(outputTarget, { recursive: true, force: true });
await rename(output, outputTarget);
console.log(JSON.stringify({ output: outputTarget, files: records.length, runtimeManifestSha256, loaderSha256 }, null, 2));
